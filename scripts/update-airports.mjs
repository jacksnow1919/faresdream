// Rebuilds src/lib/airports-all.gen.ts from Duffel's airport list, so the search
// offers every airport the flight search can use. Run: node scripts/update-airports.mjs
// Reads DUFFEL_ACCESS_TOKEN from the environment or .env.local.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const OUTPUT = "src/lib/airports-all.gen.ts";

/** Names people search for, where the standard region name differs. */
const COUNTRY_OVERRIDES = {
  AN: "Caribbean Netherlands",
  CD: "DR Congo",
  CG: "Republic of the Congo",
  CI: "Ivory Coast",
  HK: "Hong Kong",
  MM: "Myanmar",
  MO: "Macau",
  PS: "Palestine",
  TR: "Turkey",
};

function duffelToken() {
  if (process.env.DUFFEL_ACCESS_TOKEN) return process.env.DUFFEL_ACCESS_TOKEN;
  const env = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
  const token = env.match(/^DUFFEL_ACCESS_TOKEN=(.*)$/m)?.[1]?.trim();
  if (!token) throw new Error("DUFFEL_ACCESS_TOKEN is not set");
  return token;
}

async function fetchAirports(token) {
  const airports = [];
  let after = null;
  do {
    const url = new URL("https://api.duffel.com/air/airports");
    url.searchParams.set("limit", "200");
    if (after) url.searchParams.set("after", after);
    const res = await fetch(url, {
      headers: { Authorization: `Bearer ${token}`, "Duffel-Version": "v2" },
    });
    if (res.status === 429) {
      await new Promise((resolve) => setTimeout(resolve, 5000));
      continue;
    }
    if (!res.ok) throw new Error(`Duffel responded ${res.status}`);
    const body = await res.json();
    airports.push(...body.data);
    after = body.meta?.after ?? null;
  } while (after);
  return airports;
}

function countryName(code, names) {
  const name = COUNTRY_OVERRIDES[code] ?? names.of(code) ?? code;
  return name.replace(/ & /g, " and ").replace(/^St\. /, "Saint ");
}

const airports = await fetchAirports(duffelToken());
airports.sort((a, b) => a.iata_code.localeCompare(b.iata_code));

const regions = new Intl.DisplayNames(["en"], { type: "region" });
const countries = [...new Set(airports.map((a) => a.iata_country_code))].sort();
const countryNames = Object.fromEntries(countries.map((c) => [c, countryName(c, regions)]));

const rows = airports.map((a) =>
  [
    a.iata_code,
    a.name.trim(),
    a.city_name.trim(),
    a.iata_country_code,
    a.iata_city_code === a.iata_code ? "" : (a.iata_city_code ?? ""),
  ].join("|"),
);

writeFileSync(
  OUTPUT,
  `// Generated by scripts/update-airports.mjs from Duffel's airport list. Don't edit by hand.

export const COUNTRY_NAMES: Record<string, string> = ${JSON.stringify(countryNames)};

/** One airport per line: code|name|city|country code|city code (blank when it's the airport's own code). */
export const AIRPORT_ROWS = \`${rows.join("\n").replace(/[\\`$]/g, "\\$&")}\`;
`,
);
console.log(`${OUTPUT}: ${rows.length} airports in ${countries.length} countries`);
