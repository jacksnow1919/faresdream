// Rebuilds src/lib/airlines.gen.ts from Duffel's airline list. PKFARE and mcontent send only
// airline codes, so this supplies the names and logos. Run: node scripts/update-airlines.mjs
// Reads DUFFEL_ACCESS_TOKEN from the environment or .env.local.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const OUTPUT = "src/lib/airlines.gen.ts";

function duffelToken() {
  if (process.env.DUFFEL_ACCESS_TOKEN) return process.env.DUFFEL_ACCESS_TOKEN;
  const env = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
  const token = env.match(/^DUFFEL_ACCESS_TOKEN=(.*)$/m)?.[1]?.trim();
  if (!token) throw new Error("DUFFEL_ACCESS_TOKEN is not set");
  return token;
}

async function fetchAirlines(token) {
  const airlines = [];
  let after = null;
  do {
    const url = `https://api.duffel.com/air/airlines?limit=200${after ? `&after=${after}` : ""}`;
    const res = await fetch(url, {
      headers: {
        Authorization: `Bearer ${token}`,
        "Duffel-Version": "v2",
        Accept: "application/json",
      },
    });
    if (!res.ok) throw new Error(`Duffel answered ${res.status}`);
    const body = await res.json();
    airlines.push(...body.data);
    after = body.meta?.after ?? null;
  } while (after);
  return airlines;
}

const airlines = (await fetchAirlines(duffelToken()))
  .filter((a) => /^[A-Z0-9]{2}$/.test(a.iata_code ?? "") && a.name)
  .sort((a, b) => a.iata_code.localeCompare(b.iata_code));

const lines = airlines.map((a) => {
  const logo = a.logo_symbol_url ? `, logo: ${JSON.stringify(a.logo_symbol_url)}` : "";
  return `  ${JSON.stringify(a.iata_code)}: { name: ${JSON.stringify(a.name)}${logo} },`;
});

writeFileSync(
  OUTPUT,
  `// Generated by scripts/update-airlines.mjs from Duffel's airline list. Don't edit by hand.
export const AIRLINES: Record<string, { name: string; logo?: string }> = {
${lines.join("\n")}
};
`,
);
console.log(`Wrote ${airlines.length} airlines to ${OUTPUT}`);
