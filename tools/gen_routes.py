"""batch JSON (kroute.py) -> src/lib/route-data.gen.ts. usage: gen_routes.py checked_date in1.json [in2.json...]"""
import json, sys, re
checked = sys.argv[1]
data = {}
for f in sys.argv[2:]:
    data.update(json.load(open(f)))

def code(seg):
    return seg.rsplit("-", 1)[1]

def vals(v, k, nd=0):
    b = v.get(k) or {}
    x = b.get("values")
    return [round(float(i), nd) if nd else round(float(i)) for i in x] if x else None

def labels(v, k):
    return (v.get(k) or {}).get("labels")

out = []
for path, v in data.items():
    a, b = path.split("/")
    m = vals(v, "monthlyFlightPrice")
    if not m or len(m) != 12:
        print("skip (no monthly)", path, file=sys.stderr); continue
    rng = v.get("range")
    book = vals(v, "cheapestTimeToBook")
    airlines = labels(v, "cheapestAirlines") or []
    aprices = vals(v, "cheapestAirlines") or []
    pun_l = labels(v, "flightDelayMostPunctualAirline") or []
    pun_v = vals(v, "flightDelayMostPunctualAirline") or []
    rec = {
        "key": f"{code(a)}-{code(b)}",
        "source": v["url"],
        "checked": checked,
        "monthly": m,
        "weekday": vals(v, "cheapestTimeToFlyDaily"),
        "range": [int(x.replace(",", "")) for x in rng] if rng else None,  # [low, high, avg]
        "bookWeeks": book,  # index 0 = 26 weeks before ... last = 1 week before
        "cheapestAirlines": [{"name": n, "price": p} for n, p in zip(airlines, aprices)],
        # On-time %: drop tiny samples that KAYAK reports (anything under 50% is noise here)
        "onTime": [{"name": n, "pct": p} for n, p in zip(pun_l, pun_v) if p >= 50],
        "directPerDay": vals(v, "directFlightsDay"),
        "departTimes": vals(v, "flightsDepartureTime"),
        "delayByMonth": vals(v, "flightDelayFrequency"),
        "direct": {"airlines": v["direct"][0], "duration": v["direct"][1]} if v.get("direct") else None,
    }
    out.append(rec)

ts = ["// GENERATED by tools/gen_routes.py from KAYAK public route pages. Do not edit by hand.",
      "// Prices: KAYAK round-trip medians/averages from searches over the past 12 months (USD).",
      'import type { RouteFareData } from "./route-pages.ts";', "",
      "export const routeFareData: Record<string, RouteFareData> = " + json.dumps({r["key"]: r for r in out}, indent=1) + ";", ""]
open("src/lib/route-data.gen.ts", "w").write("\n".join(ts))
print("wrote", len(out), "routes", file=sys.stderr)
